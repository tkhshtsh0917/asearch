"""Generate only ja-basic-v1's kana data from the pinned Unicode 17 UCD."""

import hashlib
import pathlib
import subprocess
import sys

SHA256 = "2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c"
source = pathlib.Path(sys.argv[1]).read_bytes()
if hashlib.sha256(source).hexdigest() != SHA256:
    raise SystemExit("Expected Unicode 17.0.0 UnicodeData.txt")

halfwidth = []
compositions = []
for line in source.decode("utf-8").splitlines():
    fields = line.split(";")
    code = int(fields[0], 16)
    decomposition = fields[5].split()
    if 0xFF61 <= code <= 0xFF9F:
        if len(decomposition) != 2 or decomposition[0] != "<narrow>":
            raise SystemExit("Unexpected halfwidth decomposition")
        halfwidth.append(int(decomposition[1], 16))
    if (
        0x3040 <= code <= 0x30FF
        and len(decomposition) == 2
        and decomposition[1] in ("3099", "309A")
    ):
        compositions.append(
            (int(decomposition[0], 16), int(decomposition[1], 16), code)
        )

if len(halfwidth) != 63:
    raise SystemExit("Unexpected halfwidth range")
output = [
    "// Generated by tools/unicode/generate.py from Unicode 17.0.0.",
    f"// UnicodeData.txt SHA256: {SHA256}",
    "// Unicode-3.0 license: vendor/unicode/LICENSE.txt. Do not edit by hand.",
    "pub(super) const HALFWIDTH: [u16; 63] = [",
]
for start in range(0, len(halfwidth), 8):
    output.append(
        "    " + " ".join(f"0x{n:04x}," for n in halfwidth[start : start + 8])
    )
output.extend(
    [
        "];",
        "",
        "pub(super) const COMPOSITIONS: &[(u16, u16, u16)] = &[",
    ]
)
for base, mark, combined in sorted(compositions):
    output.append(f"    (0x{base:04x}, 0x{mark:04x}, 0x{combined:04x}),")
output.append("];")
formatted = subprocess.run(
    ["rustfmt", "--emit", "stdout", "--edition", "2024"],
    input="\n".join(output) + "\n",
    text=True,
    capture_output=True,
    check=True,
    cwd=pathlib.Path(__file__).resolve().parents[2],
)
print(formatted.stdout, end="")
